#pragma once
#include <Arduino.h>
#include <Preferences.h>
#include <esp_random.h>
#include "log.h"

// Опознание посоха: постоянный номер, который переживает выключение и перепрошивку.
// Зачем он нужен помимо MAC: счётчик номеров бросков лежит в той же памяти NVS.
// Если NVS когда-нибудь потрётся (смена схемы разделов, стирание флеш при заливке),
// счётчик начнёт с единицы, и приложение должно понять, что нумерация началась заново,
// а не свалить старые и новые броски в одну кучу. Новый staffId и есть этот признак.
// MAC для такой роли не годится: он в чипе и переживает стирание NVS.

uint32_t staffId = 0;

// Читает номер посоха из флеш, а при первом запуске придумывает его.
// Вызывать один раз в setup() и обязательно ПОСЛЕ bleBegin(): аппаратный генератор
// случайных чисел у ESP32 полноценен только при включённом радио, а номер придумывается
// один раз и навсегда. Ноль как номер не используем: он значит «не задан».
void identityBegin() {
  Preferences prefs;
  prefs.begin("staff", false);
  staffId = prefs.getUInt("id", 0);
  if (staffId == 0) {
    do {
      staffId = esp_random();
    } while (staffId == 0);
    prefs.putUInt("id", staffId);
    logLine(LOG_ID, LOG_INFO, "номер посоха придуман впервые, %u", staffId);
  } else {
    logLine(LOG_ID, LOG_INFO, "номер посоха %u", staffId);
  }
  prefs.end();
}
