// ===== Размеры =====
const int RING_LEDS    = 12;   // светодиодов в кольце
// Потолок яркости кольца, из 255. Всё кольцо белым на полной яркости тянет около 0,7 А
// по 5 В, это на пределе для USB компьютера и тяжело для MT3608. На 100 огонь тянет
// около 0,15 А: у него нет синей составляющей.
const uint8_t RING_BRIGHTNESS_MAX = 100;
// Свечение кристалла по кнопке «Свет», из 255 поверх потолка выше. Тускло 40 — это около 16
// из 255 на самом кольце, ярко 160 — около 63. Расход на них в расчёте от 2026-10-29: тускло
// одним цветом ~22 мА от аккумулятора, ярко двумя цветами ~180 мА. Подбираются на глаз.
const uint8_t GLOW_DIM_LEVEL    = 40;
const uint8_t GLOW_BRIGHT_LEVEL = 160;
const int MAX_DICE    = 10;   // максимум костей в одном броске
const int HISTORY_SIZE = 20;   // сколько последних бросков листается на посохе кнопками ◄ ► (решение автора 2026-10-29, было 5)
const int HISTORY_PAGE = 4;    // бросков на одном экране истории

// Отдельная история во флеш: её догружает приложение, когда подключается после перерыва.
// Это другая сущность, чем HISTORY_SIZE выше, и в ответе info телефону уходит именно она.
// 1500 записей по 36 байт это 54 КБ. Раздел под файлы 128 КБ, свободно 120 КБ (замер
// 2026-09-18), так что больше половины остаётся свободным: LittleFS пишет копированием
// блоков и на забитой под завязку файловой системе работает плохо.
const uint16_t HISTORY_FLASH_SIZE = 1500;

// ===== Тайминги, миллисекунды =====
const unsigned long DEBOUNCE_MS         = 30;      // кнопка должна держаться столько, чтобы засчитаться
const unsigned long BUTTONS_POLL_MS     = 10;      // как часто читаем расширитель кнопок по шине
const unsigned long BUTTONS_RETRY_MS    = 1000;    // как часто ищем пропавший расширитель
const unsigned long LONG_PRESS_MS       = 2000;    // долгое нажатие служебной кнопки
// Взвод не спадает сам (решение автора 2026-10-28, раньше 5 мин): только сброс или бросок.
// Возврат к часам и сон экрана выбираются в меню, их ступени ниже, в разделе «Меню посоха».
const unsigned long STRIKE_GUARD_MS     = 300;     // после нажатия кнопки удар не считаем
const unsigned long STRIKE_COOLDOWN_MS  = 5000;    // после броска датчик не слушаем: стол ещё дрожит, посох звенит
const unsigned long STRIKE_WINDOW_MS    = 100;     // окно, в котором считаем переключения датчика
const int           STRIKE_MIN_EDGES    = 10;       // от скольких переключений в окне пачка считается ударом
const unsigned long ROLL_ANIM_MS        = 1100;    // длительность барабана на экране: как в приложении (решение автора 2026-10-22, было 1500)
const unsigned long BATTERY_PERIOD_MS   = 10000;   // как часто мерить заряд

// ===== Меню посоха (SPEC 2.5, решения автора 2026-10-29) =====
// Каждая настройка хранится во флеш номером ступени в своей таблице. Значения по умолчанию —
// номер ступени, они же действуют до первого сохранения из меню.
const uint8_t BRIGHT_LEVELS[]  = { 51, 102, 153, 204, 255 };   // подсветка экрана: 20, 40, 60, 80, 100 %
const int     BRIGHT_DEFAULT   = 4;                            // 100 %
const uint8_t VOLUME_LEVELS[]  = { 10, 35, 100 };              // заполнение ШИМ пищалки, % от громкого; подбирается на слух
const char* const VOLUME_NAMES[] = { "LOW", "MID", "HIGH" };
const int     VOLUME_DEFAULT   = 2;                            // громко
// Возврат к часам: результат броска, история и меню без нажатий. Сон всегда дольше возврата,
// поэтому меню не даёт выбрать сон короче или равный возврату и наоборот.
const unsigned long CLOCK_TIMEOUTS_MS[] = { 30000, 60000, 90000, 120000, 180000 };   // 30 с, 1, 1,5, 2, 3 мин
const int           CLOCK_DEFAULT       = 2;                                         // 1,5 мин (решение автора 2026-10-28)
const unsigned long SLEEP_TIMEOUTS_MS[] = { 60000, 120000, 150000, 300000 };         // 1, 2, 2,5, 5 мин
const int           SLEEP_DEFAULT       = 1;                                         // 2 мин (решение автора 2026-10-28)
const int BRIGHT_COUNT = sizeof(BRIGHT_LEVELS) / sizeof(BRIGHT_LEVELS[0]);
const int VOLUME_COUNT = sizeof(VOLUME_LEVELS) / sizeof(VOLUME_LEVELS[0]);
const int CLOCK_COUNT  = sizeof(CLOCK_TIMEOUTS_MS) / sizeof(CLOCK_TIMEOUTS_MS[0]);
const int SLEEP_COUNT  = sizeof(SLEEP_TIMEOUTS_MS) / sizeof(SLEEP_TIMEOUTS_MS[0]);

// ===== Аккумулятор: границы для перевода напряжения в проценты =====
const int BATTERY_FULL_MV  = 4200;   // 100 %
const int BATTERY_EMPTY_MV = 3300;   // 0 %
const int BATTERY_LOG_STEP_PCT = 5;  // заряд пишется в журнал при старте и потом, когда изменился на столько

// ===== Служебные кнопки и кнопки меню: входы второго расширителя (I2C_ADDR_SERVICE) =====
// Подключение: hardware/wiring.md, что делают: SPEC, раздел 2.5.
const int BTN_RESET   = 0;   // Сброс
const int BTN_REPEAT  = 1;   // Повтор
const int BTN_LIGHT   = 2;   // Свет
const int BTN_SILENT  = 3;   // Тихо
const int BTN_OK      = 4;   // ОК
const int BTN_PREV    = 5;   // ◄ Назад
const int BTN_NEXT    = 6;   // ► Вперёд
const int BTN_CANCEL  = 7;   // Отмена

// ===== Тестовый режим d20: ТОЛЬКО ДЛЯ ПРОВЕРКИ =====
// Броски 1d20 идут по кругу: случайный, 20, случайный, 1. Так вспышки и звуки
// на 20 и на 1 проверяются за четыре броска, а не за полсотни. Подменённые броски
// честно уходят в историю и на планшет как обычные. При старте в журнале предупреждение,
// на экране взвода 1d20 пометка TEST. С 0.18.0 включается и выключается в меню посоха
// и помнится во флеш; это значение действует только до первого сохранения из меню.
const bool TEST_D20_CYCLE = true;

// ===== Кости в порядке кнопок слева направо =====
// Это значения по умолчанию. Рабочая таблица живёт во флеш и меняется командой map
// с планшета, см. diceSides в dice.h. Два байта на грань по той же причине, что
// и в Roll: кнопке можно назначить d1000.
const uint16_t DICE_SIDES_DEFAULT[8] = { 2, 4, 6, 8, 10, 12, 20, 100 };
const uint16_t DICE_SIDES_MAX        = 1000;   // больше не влезет в два байта вместе с суммой

// ===== Выдача истории на планшет =====
// Сколько бросков отдаём за одну команду hist. Одно событие занимает от 5 до 25 мс,
// и всё это время главный цикл не опрашивает датчик. 50 записей это около секунды,
// дальше приложение просит следующую порцию. Отдать все 1500 разом значило бы
// заморозить посох почти на минуту.
const uint16_t HIST_BATCH_SIZE = 50;

// ===== Защита подключения (задача B5) =====
// Правила целиком - в docs/ПЛАН-APP.md, разделы «Авторизация» и «PIN».
const int           PIN_LENGTH       = 4;       // ровно четыре цифры, хранится строкой
const unsigned long AUTH_TIMEOUT_MS  = 10000;   // столько ждём команду auth, потом рвём связь сами

// Лестница пауз при подборе PIN: промахи считаются подряд, верный PIN обнуляет счётчик.
// Пауза назначается на каждом третьем промахе. При такой лестнице перебор всех 10 000
// комбинаций растягивается примерно на четыре месяца непрерывного стука в посох.
// Счётчик живёт в оперативной памяти и обнуляется выключением - это сознательно:
// тумблер на рукояти, кто дотянулся до него, дотянется и до винтов, зато флеш
// не изнашивается неудачными попытками.
const uint32_t AUTH_BLOCK_3_S  = 60;     // после третьего промаха подряд
const uint32_t AUTH_BLOCK_6_S  = 300;    // после шестого
const uint32_t AUTH_BLOCK_9_S  = 600;    // после девятого
const uint32_t AUTH_BLOCK_12_S = 3600;   // после двенадцатого и дальше на каждом третьем
