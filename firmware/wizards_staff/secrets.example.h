// Образец файла с секретами. Скопируйте его рядом под именем secrets.h и впишите свой PIN.
// Сам secrets.h в репозиторий не входит: он закрыт в .gitignore, потому что попавший
// в коммит секрет остаётся в истории навсегда, даже если удалить его следующим коммитом.
//
// PIN — ровно четыре цифры, и обязательно строкой в кавычках. Числом нельзя: «0042»
// превратилось бы в 42 и перестало совпадать с тем, что набирают на планшете.
//
// ВАЖНО, когда вписывать. При первом запуске посох берёт PIN отсюда и кладёт к себе
// во флеш (NVS). Дальше он читает только флеш, а этот файл больше не смотрит — иначе
// вышла бы ловушка «поменял в файле, залил, а PIN остался старый». Поэтому свой PIN
// нужно вписать ДО первой заливки прошивки с защитой. Если уже залили со значением
// по умолчанию, менять придётся командой с планшета: {"cmd":"pin","old":"0000","new":"…"}.
//
// Если оставить пустую строку "", посох будет работать без защиты и честно скажет
// об этом планшету полем pinset: false в ответе на info.

#define STAFF_PIN "0000"
